import glob
used = set()
for f in sorted(glob.glob(D + '[bc][12]_*.txt')):
    out = []
    for l in open(f, encoding='utf-8'):
        if l.startswith('#') or not l.strip(): out.append(l); continue
        c = l.rstrip('\n').split('|')
        while len(c) < 5: c.append('')
        key = c[0].strip()
        if key in ADD:
            used.add(key)
            es_add, en_add = ADD[key]
            for i, extra in ((2, es_add), (3, en_add)):
                have = [x.strip() for x in c[i].split(',') if x.strip()]
                low = {h.lower().lstrip('~') for h in have} | {c[0].lower(), c[1].lower()}
                have += [x for x in extra if x.lower() not in low]
                c[i] = ','.join(have)
        out.append('|'.join(c) + '\n')
    open(f, 'w', encoding='utf-8').writelines(out)
missing = set(ADD) - used
print('updated', len(used), 'cards; not found:', sorted(missing))
